create role anon nologin;
create role authenticated nologin;
create role service_role nologin bypassrls;
create role authenticator login password 'local-test-only' noinherit;
grant anon, authenticated, service_role to authenticator;
create role supabase_auth_admin login password 'local-test-only' createrole;
create role supabase_storage_admin login password 'local-test-only' bypassrls;
create schema auth authorization supabase_auth_admin;
create schema storage authorization supabase_storage_admin;
create schema extensions;
create extension if not exists pgcrypto with schema extensions;
grant usage on schema public, auth, storage, extensions to anon, authenticated, service_role;
grant all on schema public to service_role;
grant all on schema storage to supabase_storage_admin;
grant all on schema auth to supabase_auth_admin;
grant all on schema public to supabase_auth_admin;
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claims',true)::jsonb->>'sub','')::uuid $$;
create function auth.role() returns text language sql stable as $$ select current_setting('request.jwt.claims',true)::jsonb->>'role' $$;
create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
alter default privileges for role postgres in schema public grant all on tables to service_role;
alter default privileges for role postgres in schema public grant all on sequences to service_role;
alter default privileges for role supabase_storage_admin in schema storage grant all on tables to service_role;
alter default privileges for role supabase_storage_admin in schema storage grant all on sequences to service_role;
grant anon, authenticated, service_role to supabase_storage_admin;
alter function auth.uid() owner to supabase_auth_admin;
alter function auth.role() owner to supabase_auth_admin;
alter function auth.jwt() owner to supabase_auth_admin;
grant create on database postgres to supabase_storage_admin;
alter role supabase_auth_admin set search_path=auth,public,extensions;
alter role supabase_storage_admin set search_path=storage,public,extensions;
